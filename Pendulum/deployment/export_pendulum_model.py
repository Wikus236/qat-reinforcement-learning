from Pendulum.paths import APP_ROOT
import argparse
import math
import re
from pathlib import Path

import numpy as np
import torch


SCRIPT_DIR = APP_ROOT
DEFAULT_MODEL_PATH = (
    APP_ROOT / "models/original"
    / "dqn_qat_linear_pendulum_base_best.zip"
    
)
DEFAULT_OUTPUT_PATH = (
    APP_ROOT / "firmware" / "sketch_sep21a" / "model_data.h"
)
DEFAULT_FULL_DQN_OUTPUT_PATH = (
    APP_ROOT / "firmware" / "full_dqn" / "model_data.h"
)
DEFAULT_DIAGNOSTIC_OUTPUT_PATH = (
    APP_ROOT / "firmware" / "diagnostic" / "model_data.h"
)

WEIGHT_PATTERN = re.compile(r"net\.(\d+)\.linear\.weight$")
ACTIVATION_SCALE_PATTERN = re.compile(r"net\.(\d+)\.scale$")


def format_float(value):
    formatted = f"{float(value):.9g}"
    if "." not in formatted and "e" not in formatted.lower():
        formatted += ".0"
    return formatted + "f"


def format_array(values, formatter, values_per_line):
    flat_values = np.asarray(values).reshape(-1)
    lines = []

    for start in range(0, len(flat_values), values_per_line):
        chunk = flat_values[start : start + values_per_line]
        lines.append("    " + ", ".join(formatter(value) for value in chunk))

    return ",\n".join(lines)


def quantize_weights(weights):
    qmax = 127
    max_abs = float(weights.abs().max().item())

    if max_abs == 0.0:
        scale = 1.0
        quantized = torch.zeros_like(weights, dtype=torch.int8)
    else:
        scale = max_abs / qmax
        quantized = torch.round(weights / scale).clamp(-qmax, qmax).to(torch.int8)

    return quantized.cpu().numpy(), scale


def extract_model(checkpoint):
    if "q_net_state_dict" not in checkpoint:
        raise ValueError("Checkpoint does not contain q_net_state_dict")

    state_dict = checkpoint["q_net_state_dict"]
    weight_entries = []

    for key, weights in state_dict.items():
        match = WEIGHT_PATTERN.fullmatch(key)
        if match is None:
            continue

        module_index = int(match.group(1))
        bias_key = f"net.{module_index}.linear.bias"
        if bias_key not in state_dict:
            raise KeyError(f"Missing bias tensor for {key}")

        quantized_weights, scale = quantize_weights(weights.cpu())
        weight_entries.append(
            {
                "module_index": module_index,
                "weights": quantized_weights,
                "scale": scale,
                "bias": state_dict[bias_key].detach().cpu().numpy().astype(np.float32),
            }
        )

    layers = sorted(weight_entries, key=lambda layer: layer["module_index"])
    if not layers:
        raise ValueError("No FakeQuantLinear layers were found in the checkpoint")

    # Float ReLU activations also apply when exporting learned weights from
    # older activation-QAT checkpoints, matching the pendulum model loader.
    activation_scales = []

    for layer_index in range(1, len(layers)):
        previous_outputs = layers[layer_index - 1]["weights"].shape[0]
        current_inputs = layers[layer_index]["weights"].shape[1]
        if previous_outputs != current_inputs:
            raise ValueError("Adjacent network layer dimensions do not match")

    return layers, activation_scales


def write_header(model_path, output_path, layers, activation_scales):
    input_size = int(layers[0]["weights"].shape[1])
    output_size = int(layers[-1]["weights"].shape[0])
    layer_inputs = [int(layer["weights"].shape[1]) for layer in layers]
    layer_outputs = [int(layer["weights"].shape[0]) for layer in layers]

    lines = [
        "#pragma once",
        "#include <stdint.h>",
        "",
        "// Generated by export_pendulum_model.py.",
        f"// Source: {model_path.name}",
        "using model_weight_t = int8_t;",
        "constexpr bool MODEL_WEIGHTS_ARE_QUANTIZED = true;",
        f"constexpr int MODEL_INPUT_SIZE = {input_size};",
        f"constexpr int MODEL_OUTPUT_SIZE = {output_size};",
        f"constexpr int MODEL_NUM_LAYERS = {len(layers)};",
        f"constexpr int MODEL_NUM_ACTIVATION_SCALES = {len(activation_scales)};",
        "constexpr int MODEL_ACTION_CLOSE = 0;",
        "constexpr int MODEL_ACTION_STOP = 1;",
        "constexpr int MODEL_ACTION_FAR = 2;",
        "",
    ]

    for layer_index, layer in enumerate(layers):
        lines.extend(
            [
                f"const model_weight_t LAYER_{layer_index}_WEIGHTS[] = {{",
                format_array(layer["weights"], lambda value: str(int(value)), 16),
                "};",
                "",
                f"const float LAYER_{layer_index}_BIAS[] = {{",
                format_array(layer["bias"], format_float, 8),
                "};",
                "",
            ]
        )

    lines.extend(
        [
            "const int LAYER_INPUT_SIZES[] = {",
            "    " + ", ".join(str(value) for value in layer_inputs),
            "};",
            "",
            "const int LAYER_OUTPUT_SIZES[] = {",
            "    " + ", ".join(str(value) for value in layer_outputs),
            "};",
            "",
            "const float LAYER_SCALES[] = {",
            "    " + ", ".join(format_float(layer["scale"]) for layer in layers),
            "};",
            "",
            "const float ACTIVATION_SCALES[] = {",
            # Zero scales bypass activation rounding in existing Arduino sketches.
            "    " + ", ".join(format_float(value) for value in
                                  (activation_scales or [0.0] * max(1, len(layers) - 1))),
            "};",
            "",
            "const model_weight_t* const LAYER_WEIGHTS[] = {",
            "    " + ", ".join(
                f"LAYER_{index}_WEIGHTS" for index in range(len(layers))
            ),
            "};",
            "",
            "const float* const LAYER_BIASES[] = {",
            "    " + ", ".join(
                f"LAYER_{index}_BIAS" for index in range(len(layers))
            ),
            "};",
            "",
        ]
    )

    output_path.parent.mkdir(parents=True, exist_ok=True)
    output_path.write_text("\n".join(lines), encoding="utf-8")


def run_exported_network(states, layers, activation_scales):
    values = np.asarray(states, dtype=np.float32)

    for layer_index, layer in enumerate(layers):
        weights = (
            layer["weights"].astype(np.float32) * np.float32(layer["scale"])
        )
        values = values @ weights.T + layer["bias"]

        if layer_index < len(layers) - 1:
            values = np.maximum(values, 0.0)


    return values


def run_checkpoint_network(states, checkpoint):
    state_dict = checkpoint["q_net_state_dict"]
    values = torch.tensor(states, dtype=torch.float32)
    linear_module_indices = sorted(
        int(match.group(1))
        for key in state_dict
        if (match := WEIGHT_PATTERN.fullmatch(key)) is not None
    )
    activation_module_indices = sorted(
        int(match.group(1))
        for key in state_dict
        if (match := ACTIVATION_SCALE_PATTERN.fullmatch(key)) is not None
    )

    for layer_index, module_index in enumerate(linear_module_indices):
        weights = state_dict[f"net.{module_index}.linear.weight"].cpu()
        bias = state_dict[f"net.{module_index}.linear.bias"].cpu()
        qweights, scale = quantize_weights(weights)
        dequantized_weights = torch.tensor(qweights, dtype=torch.float32) * scale
        values = torch.nn.functional.linear(values, dequantized_weights, bias)

        if layer_index < len(linear_module_indices) - 1:
            values = torch.relu(values)


    return values.numpy()


def verify_export(checkpoint, layers, activation_scales, sample_count, seed):
    rng = np.random.default_rng(seed)
    # Cover the 800 mm rail and the widest cart-speed training range.
    states = np.column_stack(
        (
            rng.uniform(-0.44, 0.44, sample_count),
            rng.uniform(-0.38, 0.38, sample_count),
            rng.uniform(-math.pi, math.pi, sample_count),
            rng.uniform(-15.0, 15.0, sample_count),
        )
    ).astype(np.float32)

    checkpoint_values = run_checkpoint_network(states, checkpoint)
    exported_values = run_exported_network(states, layers, activation_scales)
    maximum_error = float(np.max(np.abs(checkpoint_values - exported_values)))
    actions_match = np.array_equal(
        np.argmax(checkpoint_values, axis=1),
        np.argmax(exported_values, axis=1),
    )

    if not actions_match or maximum_error > 1e-4:
        raise RuntimeError(
            "Export verification failed: "
            f"actions_match={actions_match}, maximum_q_error={maximum_error:.8g}"
        )

    print(
        f"Verified {sample_count} states: all actions match; "
        f"maximum Q-value error={maximum_error:.8g}"
    )


def main():
    parser = argparse.ArgumentParser(
        description="Export a trained QAT pendulum DQN to an Arduino header."
    )
    parser.add_argument("--model", type=Path, default=DEFAULT_MODEL_PATH)
    parser.add_argument("--output", type=Path, default=DEFAULT_OUTPUT_PATH)
    parser.add_argument(
        "--full-dqn-output",
        type=Path,
        default=DEFAULT_FULL_DQN_OUTPUT_PATH,
    )
    parser.add_argument(
        "--diagnostic-output",
        type=Path,
        default=DEFAULT_DIAGNOSTIC_OUTPUT_PATH,
    )
    parser.add_argument("--verify-samples", type=int, default=1000)
    parser.add_argument("--seed", type=int, default=42)
    args = parser.parse_args()

    model_path = args.model.expanduser().resolve()
    output_path = args.output.expanduser().resolve()
    full_dqn_output_path = args.full_dqn_output.expanduser().resolve()
    diagnostic_output_path = args.diagnostic_output.expanduser().resolve()

    checkpoint = torch.load(model_path, map_location="cpu", weights_only=False)
    layers, activation_scales = extract_model(checkpoint)
    if args.verify_samples > 0:
        verify_export(
            checkpoint,
            layers,
            activation_scales,
            args.verify_samples,
            args.seed,
        )

    output_paths = dict.fromkeys(
        (output_path, full_dqn_output_path, diagnostic_output_path)
    )
    for path in output_paths:
        write_header(model_path, path, layers, activation_scales)

    layer_sizes = [layers[0]["weights"].shape[1]] + [
        layer["weights"].shape[0] for layer in layers
    ]
    print(f"Exported {model_path}")
    for path in output_paths:
        print(f"Header: {path}")
    print("Network: " + " -> ".join(str(size) for size in layer_sizes))
    print("Quantization: 8-bit weights only; float ReLU activations")
    print("Actions: 0=close, 1=stop, 2=far")


if __name__ == "__main__":
    main()
